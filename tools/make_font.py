#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["pillow", "fonttools"]
# ///
"""Bakes Inter into core/ui_font.inc: one byte of coverage per pixel, plus kerning for pairs of
printable ASCII. The board draws song titles from this, so the title and body faces carry every
Latin, Greek and Cyrillic letter Inter has; the small face only needs ASCII.

    uv run tools/make_font.py
"""

import os

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONTS = os.path.join(ROOT, "fonts")
ASCII = [(0x20, 0x7E)]
WIDE = ASCII + [(0xA0, 0x24F), (0x370, 0x3FF), (0x400, 0x4FF), (0x1E00, 0x1EFF), (0x2010, 0x203A), (0x20AC, 0x20AC), (0x2122, 0x2122)]
FACES = [
    ("small", "Inter-Medium.ttf", 17, ASCII + [(0xB7, 0xB7)]),
    ("body", "Inter-Medium.ttf", 24, WIDE),
    ("title", "InterDisplay-SemiBold.ttf", 34, WIDE),
]


def bake(path, px, ranges):
    with TTFont(path) as tt:
        have = set(tt.getBestCmap())
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    codes = [c for lo, hi in ranges for c in range(lo, hi + 1) if c in have or c == 0x20]
    glyphs, data = [], bytearray()
    for code in codes:
        ch = chr(code)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            offset = len(data)
            data += img.tobytes()
        else:
            offset = 0
        glyphs.append((code, round(font.getlength(ch) * 4), x0, y0, w, h, offset))
    kerns = []
    printable = [chr(c) for c in range(0x21, 0x7F)]
    for a in printable:
        for b in printable:
            k = round((font.getlength(a + b) - font.getlength(a) - font.getlength(b)) * 4)
            if k:
                kerns.append((ord(a), ord(b), k))
    return ascent, descent, glyphs, data, kerns


def main():
    out = ["// Generated by tools/make_font.py from Inter (SIL Open Font License 1.1, see fonts/LICENSE.txt).", ""]
    for name, file, px, ranges in FACES:
        ascent, descent, glyphs, data, kerns = bake(os.path.join(FONTS, file), px, ranges)
        out.append("static const uint8_t k_%s_bits[] = {" % name)
        for i in range(0, len(data), 32):
            out.append(",".join(str(b) for b in data[i:i + 32]) + ",")
        out.append("};")
        out.append("static const Glyph k_%s_glyphs[] = {" % name)
        out += ["{%d,%d,%d,%d,%d,%d,%d}," % g for g in glyphs]
        out.append("};")
        out.append("static const Kern k_%s_kerns[] = {" % name)
        out += ["{%d,%d,%d}," % k for k in kerns] or ["{0,0,0},"]
        out.append("};")
        out.append("static const Face k_%s = {%d, %d, %d, %d, k_%s_glyphs, k_%s_bits, %d, k_%s_kerns};" % (name, px, ascent, descent, len(glyphs), name, name, len(kerns), name))
        out.append("")
        print("%-5s %d px: %d glyphs, %d kerning pairs, %d KB of coverage" % (name, px, len(glyphs), len(kerns), len(data) // 1024))
    path = os.path.join(ROOT, "core", "ui_font.inc")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote core/ui_font.inc")


if __name__ == "__main__":
    main()
