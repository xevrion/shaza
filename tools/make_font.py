"""Bakes printable ASCII from Inter into core/ui_font.inc: one byte of coverage per pixel, at the
sizes the screen uses for its own words. Song titles never come through here, the relay renders
those, so ASCII is enough.

    uv run tools/make_font.py
"""

import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONT = os.path.join(ROOT, "fonts", "Inter-Medium.ttf")
SIZES = {"small": 17, "body": 24}
CHARS = [chr(c) for c in range(32, 127)] + ["·"]


def bake(px):
    font = ImageFont.truetype(FONT, px)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = Image.new("L", (max(1, w), max(1, h)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ord(ch), round(font.getlength(ch) * 4), x0, y0, w, h, len(data)))
        if w and h:
            data += img.tobytes()
    return ascent, descent, glyphs, data


def main():
    out = ["// Generated by tools/make_font.py from Inter (SIL Open Font License 1.1, see fonts/LICENSE.txt).", ""]
    for name, px in SIZES.items():
        ascent, descent, glyphs, data = bake(px)
        out.append("static const uint8_t k_%s_bits[] = {" % name)
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append("static const Glyph k_%s_glyphs[] = {" % name)
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append("static const Face k_%s = {%d, %d, %d, %d, k_%s_glyphs, k_%s_bits};" % (name, px, ascent, descent, len(glyphs), name, name))
        out.append("")
    path = os.path.join(ROOT, "core", "ui_font.inc")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d bytes)" % (path, os.path.getsize(path)))


if __name__ == "__main__":
    main()
